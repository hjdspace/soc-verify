/**
 * urg EL 文件生成（ADR 0026 决策 3 / PRD Issue #07）。
 *
 * 审批通过的 exclusion 条目由平台单向生成 urg `-elfile` 格式的排除文件：
 *   `.socverify/coverage/exclusions/<sessionId>.el`
 * 下次 Coverage Preprocessing / Coverage Recovery 的 urg 命令附加
 * `-elfile <path>` 应用——被排除项从 covered/total 计数中移出（豁免后达标语义）。
 *
 * 单向生成（审批数据 → EL），不做 EL 反向导入（ADR 0026 被拒绝项）。
 */

import { mkdir, writeFile, unlink } from 'node:fs/promises';
import { join } from 'node:path';
import type { CoverageExclusion } from '@shared/types';

const SOCVERIFY_DIR = '.socverify';
const COVERAGE_DIR = 'coverage';
const EXCLUSIONS_DIR = 'exclusions';

/** EL 文件规范路径：.socverify/coverage/exclusions/<sessionId>.el */
export function elfilePath(projectRoot: string, sessionId: string): string {
  return join(projectRoot, SOCVERIFY_DIR, COVERAGE_DIR, EXCLUSIONS_DIR, `${sessionId}.el`);
}

/**
 * 返回已存在的 EL 文件路径；不存在时返回 null。
 * Recovery / Preprocessing 构造 urg 命令前调用此函数决定是否附加 -elfile。
 */
export async function existingElfile(
  projectRoot: string,
  sessionId: string,
): Promise<string | null> {
  const path = elfilePath(projectRoot, sessionId);
  try {
    const { stat } = await import('node:fs/promises');
    const info = await stat(path);
    return info.isFile() ? path : null;
  } catch {
    return null;
  }
}

/**
 * 生成（或清空）指定 session 的 EL 文件。
 *
 * - 仅 approved 条目合并写入；每条一行注释（含审批信息）+ 一行排除指令
 * - file/line 形态：`file: <path> line: <n>`（urg EL 常用行排除语法）
 * - bin 形态：`instance: <module> bin: <bin>`（covergroup bin 排除语法）
 * - 无 approved 条目时删除既有 EL 文件（全被驳回 → 不再附加 -elfile），返回 null
 *
 * @returns 写入的 EL 文件路径；无 approved 条目时返回 null
 */
export async function generateElFile(
  projectRoot: string,
  sessionId: string,
  exclusions: CoverageExclusion[],
): Promise<string | null> {
  const approved = exclusions.filter((e) => e.status === 'approved');
  const path = elfilePath(projectRoot, sessionId);

  if (approved.length === 0) {
    // 无 approved 条目：移除既有 EL 文件（best-effort），确保后续 urg 命令不再附加
    await unlink(path).catch(() => undefined);
    return null;
  }

  const lines: string[] = [
    `# Generated by soc-verify (do not edit manually)`,
    `# Session: ${sessionId}`,
    `# Generated at: ${new Date().toISOString()}`,
    `# Approved exclusion entries: ${approved.length}`,
    `# Applied via: urg -elfile <this-file>`,
    `#`,
  ];

  for (const e of approved) {
    const selector = e.file !== undefined && e.line !== undefined
      ? `${e.file}:${e.line}`
      : (e.bin ?? '');
    lines.push(
      `# Entry: ${e.id} | module=${e.nodePath} | metric=${e.metric}` +
        ` | selector=${selector} | requested-by=${e.requestedBy}` +
        ` | approved-by=${e.approvedBy ?? 'unknown'} | reason=${e.reason}`,
    );
    if (e.file !== undefined && e.line !== undefined) {
      lines.push(`file: ${e.file} line: ${e.line}`);
    } else if (e.bin !== undefined) {
      lines.push(`instance: ${e.nodePath} bin: ${e.bin}`);
    } else {
      // 无定位信息的条目无法生成排除指令，跳过指令行（注释仍保留审计痕迹）
      lines.pop();
      lines.push(
        `# SKIPPED (no file/line or bin selector): ${e.id} module=${e.nodePath} metric=${e.metric}`,
      );
    }
  }

  const dir = join(projectRoot, SOCVERIFY_DIR, COVERAGE_DIR, EXCLUSIONS_DIR);
  await mkdir(dir, { recursive: true });
  await writeFile(path, lines.join('\n') + '\n', 'utf-8');
  return path;
}
